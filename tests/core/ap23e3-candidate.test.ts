test('AP23E3 all five physical references and 25 holiday policy bindings use the actual candidate bytes', () => {
  assert.equal(catalog.holidayBindings.length, 5);
  for (const binding of catalog.holidayBindings) {
    const previous = historical.holidayBindings.find((row: any) => row.holidayBindingId === binding.holidayBindingId);
    assert.deepEqual(binding.legalBinding, previous.legalBinding);
    assert.equal(binding.physicalBaseline.releaseId, AP23E3_RELEASE_ID);
    for (const ref of binding.physicalBaseline.references) {
      const descriptor = manifest.artifacts.find((row: any) => row.contentId === ref.contentId);
      assert.equal(ref.role, descriptor.role);
      assert.equal(ref.path, descriptor.path);
      assert.equal(ref.sha256, descriptor.sha256);
      assert.equal(ref.sha256, sha(ap23e3Files.get(ref.path)!));
    }
    for (const entry of catalog.releaseBinding.pathEligibility.filter((row: any) => row.holidayBindingId === binding.holidayBindingId)) {
      assert.equal(entry.holidayBindingSha256, objectSha(binding));
      const policy = catalog.qualificationPolicies.find((row: any) => row.pathId === entry.pathId);
      assert.equal(entry.qualificationPolicySha256, objectSha(policy));
    }
  }
});

test('AP23E3 rejects raw corruption and an omitted component', () => {
  const changed = new Map(ap23e3Files);
  changed.set(AP23E3_ADMIN_PATH, changed.get(AP23E3_ADMIN_PATH)! + ' ');
  assert.throws(() => parseFormat9LocalReferenceData(ap23e3ManifestText, changed));
  changed.delete(AP23E3_ADMIN_PATH);
  assert.throws(() => parseFormat9LocalReferenceData(ap23e3ManifestText, changed));
});

function mutatedCatalog(edit: (copy: any) => void): { manifest: string; files: Map<string, string> } {
  const copy = structuredClone(catalog);
  edit(copy);
  const text = JSON.stringify(copy, null, 2) + '\n';
  const files = new Map(ap23e3Files);
  files.set(AP23E3_ADMIN_PATH, text);
  const manifestCopy = structuredClone(manifest);
  const descriptor = manifestCopy.artifacts.find((row: any) => row.path === AP23E3_ADMIN_PATH);
  descriptor.sha256 = sha(text);
  descriptor.byteLength = Buffer.byteLength(text);
  return { manifest: JSON.stringify(manifestCopy), files };
}

test('AP23E3 rejects stale physical hashes even with a fresh enclosing manifest and policy hash', () => {
  const mutation = mutatedCatalog(copy => {
    const binding = copy.holidayBindings[0];
    binding.physicalBaseline.references[0].sha256 = '0'.repeat(64);
    for (const entry of copy.releaseBinding.pathEligibility.filter((row: any) => row.holidayBindingId === binding.holidayBindingId)) {
      entry.holidayBindingSha256 = objectSha(binding);
    }
  });
  assert.throws(() => parseFormat9LocalReferenceData(mutation.manifest, mutation.files));
});

test('AP23E3 rejects a historic physical release identity even with recomputed enclosing hashes', () => {
  const mutation = mutatedCatalog(copy => {
    const binding = copy.holidayBindings[0];
    binding.physicalBaseline.releaseId = baseline.releaseId;
    for (const entry of copy.releaseBinding.pathEligibility.filter((row: any) => row.holidayBindingId === binding.holidayBindingId)) {
      entry.holidayBindingSha256 = objectSha(binding);
    }
  });
  assert.throws(() => parseFormat9LocalReferenceData(mutation.manifest, mutation.files));
});
