import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { buildAP23E3Candidate, AP23E3_BASE, AP23E3_TARGET, AP23E3_MODULE, AP23E3_RELEASE_ID, AP23E3_ADMIN_PATH } from '../../scripts/build-ap23e3-candidate';
import { ap23e3AdministrativeContext, ap23e3ManifestText, ap23e3Files } from '../../src/release/ap23e3CandidateData';
import { parseFormat9Data, parseFormat9LocalReferenceData } from '../../src/core/releaseFormat9';
import { parseFormat8LocalReferenceData } from '../../src/core/releaseFormat8';
import { canonicalSocialJson } from '../../src/core/socialCatalog';

const sha = (value: string): string => createHash('sha256').update(value).digest('hex');
const read = (path: string): any => JSON.parse(readFileSync(path, 'utf8'));
const manifest = JSON.parse(ap23e3ManifestText);
const catalog = JSON.parse(ap23e3Files.get(AP23E3_ADMIN_PATH)!);
const historical = read('outputs/ap23e2-candidate-2026-10-18/bundle/' + AP23E3_ADMIN_PATH);
const baseline = read(`${AP23E3_BASE}/manifest.json`);
const objectSha = (value: unknown): string => sha(canonicalSocialJson(value));

test('AP23E3 exact candidate bytes form a genuine Format9 local context, never a source approval', () => {
  assert.equal(ap23e3AdministrativeContext.mode, 'localReference');
  assert.equal(ap23e3AdministrativeContext.manifest.formatVersion, '9.0.0');
  assert.equal(ap23e3AdministrativeContext.manifest.releaseId, AP23E3_RELEASE_ID);
  assert.equal(manifest.releaseStatus, 'candidate');
  assert.equal(manifest.sourceSummary.legalBasisReviewStatus, 'pending');
  assert.equal(manifest.extensions['steimer.local-reference'].calendarExportEnabled, false);
  assert.equal(manifest.extensions['steimer.local-reference'].productionActivation, false);
  assert.equal(manifest.extensions['steimer.local-reference'].sourceReleaseApproved, false);
  assert.throws(() => parseFormat9Data(ap23e3ManifestText, ap23e3Files));
  assert.throws(() => parseFormat8LocalReferenceData(ap23e3ManifestText, ap23e3Files));
});

test('AP23E3 complete raw bytes and generated preview module match integrity evidence', () => {
  assert.equal(manifest.artifacts.length, 41);
  assert.equal(ap23e3Files.size, 41);
  assert.equal(readFileSync(`${AP23E3_TARGET}/manifest.json`, 'utf8'), ap23e3ManifestText);
  for (const descriptor of manifest.artifacts) {
    const text = readFileSync(`${AP23E3_TARGET}/${descriptor.path}`, 'utf8');
    assert.equal(text, ap23e3Files.get(descriptor.path), descriptor.path);
    assert.equal(sha(text), descriptor.sha256, descriptor.path);
    assert.equal(Buffer.byteLength(text), descriptor.byteLength, descriptor.path);
  }
  const integrity = read('outputs/ap23e3-candidate-2026-10-18/bundle-integrity.json');
  for (const descriptor of [integrity.manifest, ...integrity.artifacts, integrity.previewModule]) {
    const text = readFileSync(descriptor.path, 'utf8');
    assert.equal(sha(text), descriptor.sha256, descriptor.path);
    assert.equal(Buffer.byteLength(text), descriptor.byteLength, descriptor.path);
  }
});

