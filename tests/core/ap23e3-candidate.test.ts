test('AP23E3 preserves all 44 federal rules and 50 Bern bindings without widening social eligibility', () => {
  const path = 'social-procedures/ch-social-procedures.json';
  const old = read(`${AP23E3_BASE}/${path}`);
  const current = JSON.parse(ap23e3Files.get(path)!);
  assert.equal(current.federalRules.length, 44);
  assert.equal(current.cantonalBindings.length, 50);
  for (const key of ['federalRules', 'cantonalBindings', 'suspensionProfiles', 'filingProfiles', 'excludedPaths', 'sources']) {
    assert.deepEqual(current[key], old[key], key);
  }
  assert.ok(current.cantonalBindings.every((row: any) => row.procedureContextCanton === 'BE'));
  for (const entry of current.releaseEligibility) {
    const previous = old.releaseEligibility.find((row: any) => row.bindingRef.bindingId === entry.bindingRef.bindingId);
    assert.equal(entry.status, 'candidate');
    assert.equal(entry.releaseId, AP23E3_RELEASE_ID);
    assert.equal(entry.approval, null);
    assert.deepEqual(entry.sourceReviewRef, previous.sourceReviewRef);
    assert.deepEqual(entry.referenceSuiteRef, previous.referenceSuiteRef);
    assert.deepEqual(entry.caseCoverage, previous.caseCoverage);
    assert.deepEqual(entry.calculationCoverage, previous.calculationCoverage);
    for (const ref of entry.componentRefs) assert.ok(manifest.artifacts.some((row: any) =>
      row.role === ref.role && row.contentId === ref.contentId && row.sha256 === ref.sha256));
  }
});

