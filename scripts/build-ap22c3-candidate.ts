import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { rebindSocialCalendarCandidate } from '../src/core/calendarMigration';
import { createFormat7CalculationData } from '../src/core/calculatorRuntime';
import type { SocialProcedureCatalog, ReleaseArtifactReference } from '../src/core/socialTypes';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = 'outputs/ap22c1-2026-10-08';
const target = 'outputs/ap22c3-2026-10-08/bundle';
const baseline = 'data/releases/2026-10-01-mvp-06-approved.1';
const releaseId = '2026-10-08-ap22c3-reference.1';
const sha = (bytes: string | Uint8Array): string => createHash('sha256').update(bytes).digest('hex');
const encode = (value: unknown): string => JSON.stringify(value, null, 2) + '\n';
const inventoryBytes = await readFile(resolve(root, source, 'inventory.json'));
if (sha(inventoryBytes) !== 'fd9b9d62dd838475e3651ecef646b597f514d8dc8eb9399ba2d33be89bc9a839') throw new Error('C1 inventory changed');
const inventory = JSON.parse(inventoryBytes.toString('utf8'));
const files = new Map<string, string>();
for (const artifact of inventory.artifacts) {
  const bytes = await readFile(resolve(root, source, artifact.path));
  if (sha(bytes) !== artifact.sha256 || bytes.length !== artifact.byteLength) throw new Error(`C1 bytes changed: ${artifact.path}`);
  if (!['generated-dates.json', 'date-probes.json'].includes(artifact.path)) files.set(artifact.path, bytes.toString('utf8'));
}
const refs: ReleaseArtifactReference[] = ['ch-federal-calendar', 'be-public-holidays'].map(contentId => ({
  role: 'calendar', contentId, sha256: sha(files.get(`calendars/${contentId}.json`)!)
}));
refs.push({ role: 'holidayCatalog', contentId: 'ch-holiday-catalog', sha256: sha(files.get('holiday-catalogs/ch-holiday-catalog.json')!) });
const socialPath = 'social-procedures/ch-social-procedures.json';
files.set(socialPath, encode(rebindSocialCalendarCandidate(JSON.parse(files.get(socialPath)!) as SocialProcedureCatalog, releaseId, refs)));
const baselineBytes = await readFile(resolve(root, baseline, 'manifest.json'));
if (sha(baselineBytes) !== '637cfc03c777f350031ba6c28676c685c16f25733391e1f25b0a3580016f5724') throw new Error('MVP06 baseline changed');
const old = JSON.parse(baselineBytes.toString('utf8'));
const artifacts = [...files].map(([path, text]) => {
  const value = JSON.parse(text);
  return { path, role: value.dataKind, contentId: value.dataKind === 'legalProfile' ? value.profileId : value.dataKind === 'calendar' ? value.calendarId : value.catalogId,
    mediaType: 'application/json', schemaId: value.$schema, byteLength: Buffer.byteLength(text), sha256: sha(text) };
});
const sourceIds = [...new Set([...files.values()].flatMap(text => (JSON.parse(text).sources ?? []).map((s: { sourceId: string }) => s.sourceId)))].sort();
const manifest = {
  $schema: 'https://raw.githubusercontent.com/davidsteimer/fristenrechner/main/schemas/local-reference-manifest-v7.schema.json',
  formatVersion: '7.0.0', dataKind: 'releaseManifest', releaseId, releaseStatus: 'candidate', createdOn: '2026-10-08', immutable: true,
  coverage: { from: '2026-08-29', to: null }, profileIds: old.profileIds,
  calendarIds: artifacts.filter(a => a.role === 'calendar').map(a => a.contentId),
  specialRegimeCatalogIds: old.specialRegimeCatalogIds, holidayCatalogIds: old.holidayCatalogIds,
  socialProcedureCatalogIds: old.socialProcedureCatalogIds,
  sourceSummary: { latestReviewedOn: null, legalBasisReviewStatus: 'pending', technicalValidationStatus: 'passed', sourceIds },
  providerContract: old.providerContract,
  compatibility: { ...old.compatibility, minimumConsumerFormatVersion: '7.0.0' },
  checksumAlgorithm: 'sha256', artifacts,
  extensions: { 'steimer.local-reference': { workPackage: 'AP22C3', productionActivation: false,
    sourceReleaseApproved: false, calendarExportEnabled: false,
    baseInventorySha256: sha(inventoryBytes), baseReleaseManifestSha256: sha(baselineBytes) } }
};
const manifestText = encode(manifest);
const runtime = createFormat7CalculationData(manifestText, files, { mode: 'localReference' });
for (const [path, text] of [...files, ['manifest.json', manifestText]] as [string, string][]) {
  const absolute = resolve(root, target, path);
  await mkdir(dirname(absolute), { recursive: true }); await writeFile(absolute, text);
}
// Generated raw strings preserve the manifest-bound bytes in the browser.
const module = `// SPDX-License-Identifier: AGPL-3.0-only\n// Generated by build-ap22c3-candidate.ts. Local reference only, no approval.\nimport { createFormat7CalculationData } from '../core/calculatorRuntime';\nexport const ap22c3ManifestText = ${JSON.stringify(manifestText)};\nexport const ap22c3Files: ReadonlyMap<string, string> = new Map(${JSON.stringify([...files])});\nexport const ap22c3CandidateRuntime = createFormat7CalculationData(ap22c3ManifestText, ap22c3Files, { mode: 'localReference' });\n`;
await writeFile(resolve(root, 'src/release/ap22c3CandidateData.ts'), module);
await writeFile(resolve(root, target, '../bundle-integrity.json'), encode({
  kind: 'ap22c3-local-reference-bundle', releaseId, releaseStatus: 'candidate', sourceReview: 'pending',
  productionActivation: false, referenceOnly: runtime.calendarRuntime.referenceOnly,
  manifest: { path: `${target}/manifest.json`, sha256: sha(manifestText), byteLength: Buffer.byteLength(manifestText) },
  artifacts: artifacts.map(a => ({ path: `${target}/${a.path}`, sha256: a.sha256, byteLength: a.byteLength }))
}));
console.log(JSON.stringify({ target, releaseId, artifacts: artifacts.length, calendars: runtime.calendarRuntime.calendars.length, manifestSha256: sha(manifestText), sourceReview: 'pending', referenceOnly: true }));
