export function translate(locale: Locale, key: string): string {
  const dictionary = locale === 'fr' ? fr : de;
  return dictionary[key] ?? dictionary[`reason.${key}`] ?? key;
}

export function translateReason(locale: Locale, key: string): string {
  return translate(locale, `reason.${key}`) === `reason.${key}`
    ? translate(locale, key)
    : translate(locale, `reason.${key}`);
}

export function translateBlockReason(locale: Locale, key: string): string {
  const actionKey = `block.${key}`;
  const action = translate(locale, actionKey);
  return action === actionKey ? translateReason(locale, key) : action;
}
